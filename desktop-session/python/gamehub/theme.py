"""Wallpaper, accent colour and the config files generated from them.

The desktop keeps one neutral warm-graphite palette and a single accent
colour. The accent can come from a preset, a custom pick or the colours of
the wallpaper. Every themed file (labwc, waybar, fuzzel, mako, the dock,
GTK) is rendered from a template in /usr/share/gamehub-desktop/templates
into the user's config, so changing the accent rewrites those files and
asks the running programs to reload them.
"""

