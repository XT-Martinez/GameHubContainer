# Colours

def hex_to_rgb(value):
    value = value.strip().lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return tuple(int(value[i:i + 2], 16) / 255 for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#%02x%02x%02x" % tuple(round(min(max(c, 0.0), 1.0) * 255) for c in rgb)


def mix(a, b, t):
    return tuple(x * (1 - t) + y * t for x, y in zip(a, b))


def luminance(rgb):
    def lin(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def clamp(v, lo, hi):
    return min(max(v, lo), hi)


def as_accent(rgb, min_l=0.58, max_l=0.72, min_s=0.3, max_s=0.7):
    """Pull a colour into a range that reads well on the dark surfaces."""
    h, l, s = colorsys.rgb_to_hls(*rgb)
    if s >= 0.08:
        s = clamp(s, min_s, max_s)
    return colorsys.hls_to_rgb(h, clamp(l, min_l, max_l), s)


def palette(accent):
    a = hex_to_rgb(accent)
    base = hex_to_rgb(BASE_BG)
    colours = {
        "accent": a,
        "accent_hover": mix(a, (1, 1, 1), 0.15),
        "accent_soft": mix(base, a, 0.2),
        "accent_text": mix((0.95, 0.94, 0.92), a, 0.3),
        "accent_fg": hex_to_rgb("#1c1b1a") if luminance(a) > 0.3 else hex_to_rgb("#f5f1ea"),
    }
    values = {"icon_theme": ICON_THEME,
              "accent_rgb": "%d, %d, %d" % tuple(round(c * 255) for c in a)}
    for name, rgb in colours.items():
        values[name] = rgb_to_hex(rgb)
        values[name + "_hex"] = rgb_to_hex(rgb)[1:]
    return values


# Dominant colours of images

def _pixels(pixbuf):
    data = pixbuf.get_pixels()
    n = pixbuf.get_n_channels()
    stride = pixbuf.get_rowstride()
    alpha = pixbuf.get_has_alpha()
    for y in range(pixbuf.get_height()):
        row = y * stride
        for x in range(pixbuf.get_width()):
            i = row + x * n
            if alpha and data[i + 3] < 128:
                continue
            yield data[i] / 255, data[i + 1] / 255, data[i + 2] / 255


def hue_groups(pixbuf, buckets=24):
    """Colour groups by hue, most prominent first: (weight, average rgb)."""
    sums = {}
    for rgb in _pixels(pixbuf):
        h, l, s = colorsys.rgb_to_hls(*rgb)
        if s < 0.12 or l < 0.06 or l > 0.96:
            continue
        # Favour vivid mid-tones over dark or washed-out pixels
        w = s * (1.0 - abs(l - 0.5) * 1.4)
        if w <= 0:
            continue
        b = int(h * buckets) % buckets
        acc = sums.setdefault(b, [0.0, 0.0, 0.0, 0.0])
        acc[0] += w
        acc[1] += rgb[0] * w
        acc[2] += rgb[1] * w
        acc[3] += rgb[2] * w
    groups = [(w, b, (r / w, g / w, bl / w)) for b, (w, r, g, bl) in sums.items()]
    groups.sort(reverse=True)
    return [(w, b, rgb) for w, b, rgb in groups]


def load_pixbuf(path, size):
    import gi
    gi.require_version("GdkPixbuf", "2.0")
    from gi.repository import GdkPixbuf
    return GdkPixbuf.Pixbuf.new_from_file_at_scale(str(path), size, size, True)


def wallpaper_swatches(path, count=6):
    """Accent candidates taken from a wallpaper, most prominent first."""
    try:
        groups = hue_groups(load_pixbuf(path, 96))
    except Exception:
        return []
    picked = []
    for w, b, rgb in groups:
        # Skip hues next to one already picked (24 buckets, 15 degrees each)
        if any(min((b - pb) % 24, (pb - b) % 24) < 2 for pb, _ in picked):
            continue
        picked.append((b, rgb))
        if len(picked) == count:
            break
    swatches = [rgb_to_hex(as_accent(rgb)) for _, rgb in picked]
    # A single-hue wallpaper still gets a few choices: lighter and muted
    if swatches:
        h, l, s = colorsys.rgb_to_hls(*hex_to_rgb(swatches[0]))
        for dl, ds in ((0.08, 0.0), (-0.04, -0.15), (0.04, -0.25)):
            if len(swatches) >= 4:
                break
            alt = rgb_to_hex(colorsys.hls_to_rgb(h, clamp(l + dl, 0.5, 0.8), clamp(s + ds, 0.05, 1)))
            if alt not in swatches:
                swatches.append(alt)
    return swatches


def dominant_colour(pixbuf, fallback):
    """Signature colour of an app icon, brightened for the dark dock."""
    groups = hue_groups(pixbuf)
    if not groups:
        return hex_to_rgb(fallback)
    return as_accent(groups[0][2], min_l=0.6, max_l=0.75, min_s=0.45, max_s=0.85)


# State

def default_state():
    return {"wallpaper": str(DEFAULT_WALLPAPER), "accent": DEFAULT_ACCENT,
            "auto_accent": False}


def load_state():
    state = default_state()
    try:
        state.update(json.loads(STATE_FILE.read_text()))
    except (OSError, ValueError):
        pass
    if not Path(state["wallpaper"]).is_file():
        state["wallpaper"] = str(DEFAULT_WALLPAPER)
    try:
        state["accent"] = rgb_to_hex(hex_to_rgb(state["accent"]))
    except (ValueError, AttributeError):
        state["accent"] = DEFAULT_ACCENT
    return state


def save_state(state):
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    tmp = STATE_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=2) + "\n")
    tmp.replace(STATE_FILE)


def wallpapers():
    found = []
    for folder in (WALLPAPERS, USER_WALLPAPERS):
        if folder.is_dir():
            found += sorted(p for p in folder.iterdir()
                            if p.suffix.lower() in (".svg", ".png", ".jpg", ".jpeg", ".webp"))
    return found


# Rendering

def render(name, values):
    text = (TEMPLATES / name).read_text()
    return re.sub(r"\{\{(\w+)\}\}", lambda m: values[m.group(1)], text)


def write_if_changed(path, text):
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)
    return True


def recolour_svg(text, accent):
    ah, al, as_ = colorsys.rgb_to_hls(*hex_to_rgb(accent))
    rh, rl, rs = colorsys.rgb_to_hls(*hex_to_rgb(ICON_SOURCE_BLUE))

    def swap(match):
        h, l, s = colorsys.rgb_to_hls(*hex_to_rgb(match.group(0)))
        # Only the folder blues; keep whites, greys and emblem colours
        if s < 0.25 or min(abs(h - rh), 1 - abs(h - rh)) > 0.12:
            return match.group(0)
        l2 = clamp(l + (al - rl) * 0.6, 0.0, 1.0)
        s2 = clamp(s * as_ / rs, 0.0, 1.0)
        return rgb_to_hex(colorsys.hls_to_rgb(ah, l2, s2))

    return re.sub(r"#[0-9a-fA-F]{6}\b", swap, text)


def build_icon_theme(accent):
    """Fluent with its folder icons recoloured to the accent."""
    root = DATA_HOME / "icons" / ICON_THEME
    stamp = root / ".accent"
    wanted = f"{ICON_VERSION} {accent}"
    try:
        if stamp.read_text() == wanted:
            return False
    except OSError:
        pass

    index = (ICON_SOURCE / "index.theme").read_text()
    sections = re.findall(r"^\[([^\]]+)\]\n((?:[^\[\n][^\n]*\n|\n)*)", index, re.M)
    places = [(name, body) for name, body in sections
              if name.endswith("/places") and not name.startswith("symbolic")]
    apps_dir = FILE_MANAGER_ICON.rsplit("/", 1)[0]
    places += [(name, body) for name, body in sections if name == apps_dir]

    tmp = root.with_name(root.name + ".tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    for name, _ in places:
        size_dir = name.split("/")[0]
        if "@" in size_dir:
            # Scaled directories reuse the plain size's icons
            link = tmp / size_dir
            if not link.exists():
                link.symlink_to(size_dir.split("@")[0])
            continue
        src = ICON_SOURCE / name
        if not src.is_dir():
            continue
        dst = tmp / name
        dst.mkdir(parents=True, exist_ok=True)
        if name == apps_dir:
            folder = recolour_svg((ICON_SOURCE / FILE_MANAGER_ICON).resolve().read_text(), accent)
            for icon in FILE_MANAGER_NAMES:
                (dst / (icon + ".svg")).write_text(folder)
            continue
        for entry in src.iterdir():
            target = entry.resolve()
            if not target.name.startswith("default-") or target.suffix != ".svg":
                continue
            (dst / entry.name).write_text(recolour_svg(target.read_text(), accent))

    lines = ["[Icon Theme]", f"Name={ICON_THEME}",
             "Comment=Fluent with folders and file managers in the desktop accent colour",
             f"Inherits={ICON_INHERITS}", "Example=folder",
             "Directories=" + ",".join(name for name, _ in places), ""]
    for name, body in places:
        lines += [f"[{name}]", body.strip(), ""]
    (tmp / "index.theme").write_text("\n".join(lines))
    (tmp / ".accent").write_text(wanted)

    shutil.rmtree(root, ignore_errors=True)
    tmp.replace(root)
    return True


def write_files(state):
    values = palette(state["accent"])
    values["wallpaper"] = state["wallpaper"]
    changed = set()
    # Icons first: the dock reloads them when widgets.css changes
    if build_icon_theme(state["accent"]):
        changed.add("icons")
    for name, path in OUTPUTS.items():
        if write_if_changed(path, render(name, values)):
            changed.add(name)
    for name, path in GTK_OUTPUTS.items():
        try:
            current = path.read_text()
        except OSError:
            current = None
        if current is not None and GENERATED_MARK not in current:
            continue  # the user's own file
        write_if_changed(path, render(name, values))
    return changed


# Reloading the running session

def _pids(name):
    out = subprocess.run(["pgrep", "-u", str(os.getuid()), "-x", name],
                         capture_output=True, text=True).stdout
    return [int(p) for p in out.split()]


def _signal(name, sig):
    for pid in _pids(name):
        try:
            os.kill(pid, sig)
        except OSError:
            pass


def start_wallpaper(state):
    """Start swaybg on the wallpaper, then retire any earlier instance."""
    old = _pids("swaybg")
    subprocess.Popen(["swaybg", "-c", "1c1b1a", "-i", state["wallpaper"], "-m", "fill"],
                     stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, start_new_session=True)
    if old:
        subprocess.Popen(["sh", "-c", "sleep 0.5; kill " + " ".join(map(str, old))],
                         start_new_session=True)


def reload_session(state, wallpaper_changed):
    import signal
    _signal("labwc", signal.SIGHUP)
    _signal("waybar", signal.SIGUSR2)
    subprocess.run(["makoctl", "reload"], stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL)
    if wallpaper_changed:
        start_wallpaper(state)
    # The dock watches widgets.css itself


def apply(state, reload=True, wallpaper_changed=False):
    write_files(state)
    if reload:
        reload_session(state, wallpaper_changed)


def main(argv=None):
    parser = argparse.ArgumentParser(prog="gamehub-theme",
                                     description="Wallpaper and accent colour of the GameHub desktop")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_apply = sub.add_parser("apply", help="regenerate themed files from the saved state")
    p_apply.add_argument("--no-reload", action="store_true",
                         help="only write files; do not signal running programs")
    p_set = sub.add_parser("set", help="change the wallpaper or accent and apply")
    p_set.add_argument("--wallpaper")
    p_set.add_argument("--accent", help="#rrggbb, or 'auto' to follow the wallpaper")
    sub.add_parser("wallpaper", help="start swaybg on the saved wallpaper")
    p_sw = sub.add_parser("swatches", help="print accent candidates of an image")
    p_sw.add_argument("image")
    args = parser.parse_args(argv)

    if args.cmd == "apply":
        apply(load_state(), reload=not args.no_reload, wallpaper_changed=not args.no_reload)
    elif args.cmd == "set":
        state = load_state()
        wallpaper_changed = False
        if args.wallpaper:
            state["wallpaper"] = str(Path(args.wallpaper).resolve())
            wallpaper_changed = True
        if args.accent == "auto":
            state["auto_accent"] = True
        elif args.accent:
            state["accent"] = rgb_to_hex(hex_to_rgb(args.accent))
            state["auto_accent"] = False
        if state["auto_accent"]:
            swatches = wallpaper_swatches(state["wallpaper"])
            if swatches:
                state["accent"] = swatches[0]
        save_state(state)
        apply(state, wallpaper_changed=wallpaper_changed)
    elif args.cmd == "wallpaper":
        start_wallpaper(load_state())
    elif args.cmd == "swatches":
        print("\n".join(wallpaper_swatches(args.image)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
